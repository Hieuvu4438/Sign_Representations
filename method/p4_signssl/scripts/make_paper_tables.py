"""Regenerate every quantitative table of research/paper/draft.md from raw artifacts
(rank files / result JSONs). Output: research/paper/tables.md + tables.json + fig_readout_gap.png."""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from p4.retrieval import metrics_from_ranks, paired_cluster_bootstrap, per_query  # noqa: E402

RT = Path(__file__).resolve().parents[1] / "runtime"
OUT = Path(__file__).resolve().parents[3] / "docs/proposal4/sign-ssl-research-agent/research/paper"


def clips(d):
    return [json.loads(l) for l in open(RT / "feats" / d / "clips.jsonl")]


def row(ranks, ref=None, clusters=None):
    m = metrics_from_ranks(ranks)
    out = {k: round(100 * m[k], 2) for k in ("R@1", "R@5", "MRR", "DCG")}
    if ref is not None:
        b = paired_cluster_bootstrap(per_query(ref)["R@1"], per_query(ranks)["R@1"], clusters, n_boot=10000)
        out.update(dR1=round(100 * b["diff"], 2), ci=[round(100 * x, 2) for x in b["ci95"]],
                   pos=f"{b['n_clusters_positive']}/{b['n_clusters']}" if b["n_clusters"] < 50 else None)
    return out


def main():
    T = {}
    # Table 1: confirmatory test results
    aslc = clips("aslc_test_s2"); sg = np.array([c["signer"] for c in aslc])
    r0 = np.load(RT / "eval/EX05_aslc_R0/ranks_features_activity.npy")
    T["aslc_test"] = {"R0": row(r0), "R1": row(np.load(RT / "eval/EX05_aslc_R12/ranks_bins2.npy"), r0, sg),
                      "R2": row(np.load(RT / "eval/EX05_aslc_R12/ranks_chamfer.npy"), r0, sg)}
    wl = clips("wlasl_test_s2"); cl = np.array([c["gloss"] for c in wl])
    r0 = np.load(RT / "eval/EX05_wlasl_R0/ranks_features_activity.npy")
    T["wlasl_test"] = {"R0": row(r0), "R1": row(np.load(RT / "eval/EX05_wlasl_R12/ranks_bins2.npy"), r0, cl),
                       "R2": row(np.load(RT / "eval/EX05_wlasl_R12/ranks_chamfer.npy"), r0, cl)}
    ms = clips("msasl_test_s2"); cl = np.array([c["gloss"] for c in ms])
    r0 = np.load(RT / "eval/EX07_ranks_R0.npy")
    T["msasl_test"] = {k: row(np.load(RT / f"eval/EX07_ranks_{k}.npy"), None if k == "R0" else r0, cl)
                       for k in ("R0", "R1", "R1W", "R2", "R2W")}
    # Table 2: SHuBERT val LOSO
    sh = clips("shubert_res_val"); sg = np.array([c["signer"] for c in sh])
    base = np.load(RT / "eval/EX06_shubert_res_val/ranks_S1_mean_valid.npy")
    T["shubert_val"] = {k: row(np.load(RT / f"eval/EX06_shubert_res_val/ranks_{k}.npy"), None if k.startswith("S0") or k.startswith("S1") else base, sg)
                        for k in ("S0_mean_all", "S1_mean_valid", "S2_bins2", "S3_chamfer20")}
    # Table 3: ASL Citizen val readout family (official gallery)
    vc = clips("aslc_val_s2"); sg = np.array([c["signer"] for c in vc])
    p0 = np.load(RT / "eval/EX01_official/ranks_features_activity.npy")
    fam = {"paper (activity mean)": p0, "plain mean": np.load(RT / "eval/EX01_official/ranks_features_mean.npy")}
    for k in ("wmean_span", "nmean_span", "max_span", "gem3_span"):
        fam[k] = np.load(RT / f"eval/EX01_readouts/ranks_pool_{k}.npy")
    for k in ("bins2", "bins3", "bins4", "chamfer"):
        fam[k] = np.load(RT / f"eval/EX01_readouts/ranks_{k}.npy")
    T["aslc_val_family"] = {k: row(v, None if k == "paper (activity mean)" else p0, sg) for k, v in fam.items()}
    json.dump(T, open(OUT / "tables.json", "w"), indent=1)
    md = ["# Paper tables (generated by `method/p4_signssl/scripts/make_paper_tables.py`; do not edit by hand)\n"]
    for name, tab in T.items():
        md.append(f"## {name}\n\n| readout | R@1 | R@5 | MRR | DCG | ΔR@1 vs ref [95% CI] | clusters + |\n| --- | --- | --- | --- | --- | --- | --- |")
        for k, v in tab.items():
            d = f"{v['dR1']:+.2f} [{v['ci'][0]:+.2f}, {v['ci'][1]:+.2f}]" if "dR1" in v else "ref"
            md.append(f"| {k} | {v['R@1']:.2f} | {v['R@5']:.2f} | {v['MRR']:.2f} | {v['DCG']:.2f} | {d} | {v.get('pos') or ''} |")
        md.append("")
    (OUT / "tables.md").write_text("\n".join(md))
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        ds = [("ASL Citizen", "aslc_test"), ("WLASL2000", "wlasl_test"), ("MS-ASL", "msasl_test")]
        series = (("R0", "averaged (paper)", "#2a78d6"), ("R1", "ordered 2-segment", "#eb6834"),
                  ("R2", "window-set matching", "#1baf7a"))
        x = np.arange(len(ds)); w = 0.26
        fig, ax = plt.subplots(figsize=(6.2, 3.3))
        ax.set_facecolor("#fcfcfb"); fig.patch.set_facecolor("#fcfcfb")
        for j, (k, lab, col) in enumerate(series):
            vals = [T[d][k]["R@1"] for _, d in ds]
            bars = ax.bar(x + (j - 1) * w, vals, w, label=lab, color=col, edgecolor="#fcfcfb", linewidth=2)
            for b_, (_, d) in zip(bars, ds):
                v = T[d][k]
                txt = f"{v['R@1']:.1f}" if k == "R0" else f"{v['dR1']:+.1f}"
                ax.text(b_.get_x() + b_.get_width() / 2, b_.get_height() + 0.6, txt, ha="center", va="bottom",
                        fontsize=7, color="#52514e")
        ax.set_xticks(x, [n for n, _ in ds], color="#0b0b0b"); ax.set_ylabel("test R@1 (%)", color="#52514e")
        ax.grid(axis="y", color="#e6e5e0", linewidth=0.6); ax.set_axisbelow(True)
        for sp in ("top", "right"): ax.spines[sp].set_visible(False)
        for sp in ("left", "bottom"): ax.spines[sp].set_color("#c9c8c2")
        ax.tick_params(colors="#52514e", labelsize=8)
        ax.legend(frameon=False, fontsize=8, loc="lower center", bbox_to_anchor=(0.5, 1.0), ncol=3)
        ax.set_title("Same frozen SignRep windows, three readouts (labels: R@1 or gain over averaged)", fontsize=8.5, color="#0b0b0b", pad=22)
        fig.tight_layout(); fig.savefig(OUT / "fig_readout_gap.png", dpi=160)
    except Exception as e:  # plotting is optional
        print("figure skipped:", e)
    print((OUT / "tables.md").read_text())


if __name__ == "__main__":
    main()
