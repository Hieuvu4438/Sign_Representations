"""Stage2-only author recipe, supplied via Sign2GPT main.py --config=<this file>.

Set SIGNREP_TRANSLATION_CONFIG to a JSON config generated by the baseline CLI.
No original stage1 config is invoked and no pseudo-gloss files are needed.
"""
import json
import os
from pathlib import Path
from ml_collections import config_dict


def get_config():
    user = json.loads(Path(os.environ["SIGNREP_TRANSLATION_CONFIG"]).read_text())
    if user["dataset"] not in {"phoenix14t", "csl_daily"}:
        raise ValueError("Sign2GPT integration supports Phoenix14T and CSL-Daily")
    csl = user["dataset"] == "csl_daily"
    cfg = config_dict.ConfigDict()
    cfg.name = "signrep_" + user["dataset"]
    cfg.save_dir = user["output"]
    cfg.main_runner = "trainer.complete_translation_trainer"
    cfg.project_name = cfg.name
    cfg.aug_name = None
    cfg.aug_params = {}
    cfg.bs = user.get("batch_size", 4 if csl else 8)
    cfg.accum = 1
    cfg.num_workers = user.get("num_workers", 0)
    cfg.gate_grad_multiplier = 1.
    cfg.lr = 3e-4
    cfg.lr_scheduler = "warmupwithcosine"
    cfg.lr_scheduler_params = {"lr_scale_factor": .01, "num_cycles": 1, "start_value_mult": .7,
                               "end_value_mult": .7, "warmup_epochs": 5}
    cfg.optimizer_name = "adamw"
    cfg.optimizer_params = {"lr": cfg.lr, "weight_decay": .001}
    cfg.criterion_name = "losses.base_loss"
    cfg.criterion_params = {"dict_of_loss_params": {"ce": {"cls_name": "losses.loss_functions.ce_loss",
        "loss_params": {"src_name": "logits", "tgt_name": "gt_ids", "mask_name": "gt_text_mask",
                        "label_smoothing": .1}, "weight": 1.}}}
    cfg.max_epochs = 100
    cfg.model_checkpoint_dir = ""
    for stage, split in [("train", "train"), ("valid", "val"), ("test", "test")]:
        cfg[f"{stage}_ds_name"] = "signrep_baseline.translation_sign2gpt"
        cfg[f"{stage}_ds_params"] = {"manifest": user[f"{split}_manifest"], "split": split,
            "shuffle": stage == "train", "num_workers": cfg.num_workers, "bs": cfg.bs,
            "drop_last": stage == "train"}
    cfg.lm_name = user.get("llm", "facebook/xglm-1.7B")
    cfg.additional_tokens = {}
    cfg.pretext = ""
    cfg.replacement_pickle = user.get("replacement_pickle") if csl else None
    cfg.model_name = "models.trial_models.test_stage2_model"
    cfg.model_params = {"stage1_name": "signrep_baseline.translation_sign2gpt", "stage1_params": {},
        "stage1_ckpt": None, "post_name": "models.post_models.linear_pos_head",
        "post_params": {"pos_type": "sine", "pre_pos": True}, "llm_name": cfg.lm_name,
        "lang_backbone_name": "models.huggingface.modeling_xglm", "freeze": False,
        "adaptor_params": {"adapt_layers": list(range(24)), "lora_layers": list(range(24)),
            "w_lora_ff": False, "lora_rank": 4, "lora_drop": .1, "gate_type": "clamp",
            "lora_a": 4., "adapt_tokens": False}}
    cfg.gen_params = {"max_length": 64, "temperature": 1., "num_beams": 4}
    cfg.seed = user.get("seed", 1)
    cfg.grad_clip_norm, cfg.grad_clip_value = 1., 1.
    cfg.mixup, cfg.bfloat16_only = False, False
    cfg.logger_name = ["text"]
    cfg.resume, cfg.save_ckpt = True, True
    cfg.train_length, cfg.val_length = None, None
    cfg.log_every = 100
    cfg.score_factor, cfg.score_name = 1, "valid/obleu"
    cfg.apply_metric_splitter = csl
    cfg.append_string = ""
    cfg.watch_grad = True
    cfg.max_seq_len = user.get("max_seq_len", 512)
    return cfg
